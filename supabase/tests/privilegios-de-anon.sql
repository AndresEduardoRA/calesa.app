-- 4-40: `anon` no toca `public` (`20261028224755_anon_fuera_de_public.sql`). Con `aclexplode` sobre lo que existe y sobre lo que se crea
-- después: ningún privilegio de `anon` (ni de PUBLIC en una función) en tablas, vistas, columnas, secuencias ni funciones de `public`;
-- `authenticated` sin truncate, references, trigger ni maintain, sin `select`/`update` en secuencias y sin EXECUTE en funciones de
-- trigger. Corre en `pnpm db:probar` (PGlite) y en el job `base` de CI contra la base real:
--   psql "$SUPABASE_DB_LOCAL" -v ON_ERROR_STOP=1 -f supabase/tests/privilegios-de-anon.sql

-- @test anon no tiene ningún privilegio sobre lo que existe en public
do $$
declare v text;
begin
  select string_agg(distinct d, ', ' order by d) into v from (
    -- tablas, vistas y secuencias
    select c.relname || ' (' || x.privilege_type || ')' as d
    from pg_class c cross join lateral aclexplode(coalesce(c.relacl, acldefault((case c.relkind when 'S' then 's' else 'r' end)::"char", c.relowner))) x
    where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p', 'v', 'm', 'f', 'S')
      and x.grantee = 'anon'::regrole
    union all
    -- columnas
    select c.relname || '.' || a.attname || ' (' || x.privilege_type || ')'
    from pg_attribute a join pg_class c on c.oid = a.attrelid cross join lateral aclexplode(a.attacl) x
    where c.relnamespace = 'public'::regnamespace and a.attacl is not null and x.grantee = 'anon'::regrole
    union all
    -- funciones, de anon o de PUBLIC (grantee 0)
    select p.oid::regprocedure::text || ' (EXECUTE)'
    from pg_proc p cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) x
    where p.pronamespace = 'public'::regnamespace and x.grantee in (0, 'anon'::regrole)
  ) t;
  if v is not null then raise exception 'anon (o PUBLIC) tiene privilegios en public: %', v; end if;
end $$;

-- @test authenticated no tiene lo que nunca le corresponde en public
do $$
declare v text;
begin
  select string_agg(distinct d, ', ' order by d) into v from (
    select c.relname || ' (' || x.privilege_type || ')' as d
    from pg_class c cross join lateral aclexplode(coalesce(c.relacl, acldefault('r', c.relowner))) x
    where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p', 'v', 'm', 'f')
      and x.grantee = 'authenticated'::regrole and x.privilege_type in ('TRUNCATE', 'REFERENCES', 'TRIGGER', 'MAINTAIN')
    union all
    select c.relname || ' (' || x.privilege_type || ')'
    from pg_class c cross join lateral aclexplode(coalesce(c.relacl, acldefault('s', c.relowner))) x
    where c.relnamespace = 'public'::regnamespace and c.relkind = 'S'
      and x.grantee = 'authenticated'::regrole and x.privilege_type in ('SELECT', 'UPDATE')
    union all
    select p.oid::regprocedure::text || ' (EXECUTE de un trigger)'
    from pg_proc p cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) x
    where p.pronamespace = 'public'::regnamespace and p.prorettype = 'trigger'::regtype
      and x.grantee = 'authenticated'::regrole
  ) t;
  if v is not null then raise exception 'authenticated tiene en public lo que no le corresponde: %', v; end if;
end $$;

-- @test lo que se crea después tampoco: tabla, vista, secuencia y función nuevas de postgres en public
do $$
declare v text;
begin
  create table public._prueba_privilegios (id bigint generated by default as identity primary key, x text);
  create view public._prueba_privilegios_v as select id from public._prueba_privilegios;
  create sequence public._prueba_privilegios_s;
  create function public._prueba_privilegios_f() returns int language sql as 'select 1';
  select string_agg(d, ', ' order by d) into v from (
    select c.relname || ' (' || x.privilege_type || ' a ' || coalesce(nullif(x.grantee::regrole::text, '-'), 'PUBLIC') || ')' as d
    from pg_class c cross join lateral aclexplode(coalesce(c.relacl, acldefault((case c.relkind when 'S' then 's' else 'r' end)::"char", c.relowner))) x
    where c.relname like '\_prueba\_privilegios%' and c.relnamespace = 'public'::regnamespace
      and (x.grantee = 'anon'::regrole
        or (x.grantee = 'authenticated'::regrole and c.relkind <> 'S' and x.privilege_type in ('TRUNCATE', 'REFERENCES', 'TRIGGER', 'MAINTAIN'))
        or (x.grantee = 'authenticated'::regrole and c.relkind = 'S' and x.privilege_type in ('SELECT', 'UPDATE')))
    union all
    -- Sólo el grant explícito a anon: el EXECUTE de PUBLIC es un default global de Postgres que cada función nueva quita (si una lo
    -- olvida, cae la primera prueba de este archivo).
    select '_prueba_privilegios_f (EXECUTE a anon)'
    from pg_proc p cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) x
    where p.oid = 'public._prueba_privilegios_f()'::regprocedure and x.grantee = 'anon'::regrole
  ) t;
  drop function public._prueba_privilegios_f();
  drop sequence public._prueba_privilegios_s;
  drop view public._prueba_privilegios_v;
  drop table public._prueba_privilegios;
  if v is not null then raise exception 'un objeto nuevo de public nace con privilegios de más: %', v; end if;
end $$;
